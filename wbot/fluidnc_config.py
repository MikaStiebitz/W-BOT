"""FluidNC 3.9 firmware configuration: generate, verify against ``$CD``, check boot log.

Golden reference is the working, active ``backup/config-live-2026-11-20.yaml``.
Facts baked in here (see DECISIONS.md):

* D-029  the kinematics block is named ``WallPlotter`` (the C++ class name).  A wrong
         name is *silently ignored* and FluidNC runs as a cartesian machine.
* D-030  a servo axis needs ``homing: positive_direction: false`` or every positive
         angle is clamped to the same pulse.
* D-032  (corrected, MG90S) 1000..2000 us = 180 deg -> 5.556 us/deg.  The pen axis spans
         -44..+44 deg, axis 0 = servo centre = power-up position.
* D-033  ``stepping.idle_ms`` must be 255 (= never disable): the servo signal is cut when
         the motors idle out.  The field is one byte capped at 254, so 255 is the "never".
* an ``rc_servo`` with ``output_pin: NO_PIN`` invalidates the *whole* config, so a disabled
  servo axis is omitted completely.

The generated text is plain ASCII (German comments transliterated) so that nothing in
the XMODEM upload or the FluidNC parser can trip over encoding.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from typing import Any, Literal

import yaml

from .config import Config, ServoSpec
from .servo import ServoModel

log = logging.getLogger(__name__)

KINEMATICS_NAME = "WallPlotter"
IDLE_MS = 255                       # never disable (D-033); field is a byte, max 254 otherwise
MAX_TRAVEL_BELT_MM = 2700.0
SERVO_MAX_RATE = 600000.0           # as in the live file: servo axes must not rate-limit
SERVO_ACCEL = 1000000.0
SERVO_PWM_HZ = 50
_AXIS_ORDER = ("z", "a")            # FluidNC axes after X/Y, in firmware order


class ConfigGenError(ValueError):
    """The Config cannot be expressed as a valid FluidNC configuration."""


@dataclass(frozen=True)
class Issue:
    severity: Literal["error", "warn"]
    key: str
    expected: Any
    actual: Any
    message_de: str


def has_errors(issues: list[Issue]) -> bool:
    return any(i.severity == "error" for i in issues)


# ---------------------------------------------------------------------------
# expected configuration (single source of truth for generator and verifier)
# ---------------------------------------------------------------------------
def servo_axes(cfg: Config) -> list[tuple[str, ServoSpec]]:
    """Active servo axes as ``(letter_lowercase, spec)`` in firmware order (Z, then A)."""
    specs = [cfg.servos.pen]
    if cfg.servos.revolver.enabled:
        specs.append(cfg.servos.revolver)
    out = sorted(((s.axis.lower(), s) for s in specs), key=lambda t: _AXIS_ORDER.index(t[0]))
    letters = [k for k, _ in out]
    if letters not in (["z"], ["z", "a"]):
        raise ConfigGenError(
            f"Servo-Achsen {letters}: FluidNC braucht lueckenlose Achsen (Z, dann A); "
            "der Stift muss auf Z liegen, wenn der Revolver aktiv ist")
    return out


def _servo_axis(spec: ServoSpec) -> dict:
    m = ServoModel(spec)
    return {
        "steps_per_mm": 1.0,
        "max_rate_mm_per_min": SERVO_MAX_RATE,
        "acceleration_mm_per_sec2": SERVO_ACCEL,
        "max_travel_mm": float(spec.axis_travel),
        "soft_limits": False,
        "homing": {"cycle": 0, "positive_direction": False, "mpos_mm": float(spec.axis_min)},
        "motor0": {"rc_servo": {"output_pin": spec.pin, "pwm_hz": SERVO_PWM_HZ,
                                "min_pulse_us": m.fw_min_us, "max_pulse_us": m.fw_max_us}},
    }


def _belt_axis(cfg: Config, step: str, direction: str, invert: bool) -> dict:
    return {
        "steps_per_mm": float(cfg.steps_per_mm),
        "max_rate_mm_per_min": float(cfg.firmware.max_rate_mm_min),
        "acceleration_mm_per_sec2": float(cfg.motion.acceleration_mm_s2),
        "max_travel_mm": MAX_TRAVEL_BELT_MM,
        "soft_limits": False,
        "homing": {"cycle": 0},
        "motor0": {"stepstick": {"step_pin": step,
                                 "direction_pin": direction + ":low" if invert else direction}},
    }


def expected_config(cfg: Config) -> dict:
    """The FluidNC configuration as a nested dict (key order = file order)."""
    (lx, ly), (rx, ry) = cfg.fw_anchor_left, cfg.fw_anchor_right
    axes: dict[str, Any] = {
        "shared_stepper_disable_pin": "I2SO.0",
        "x": _belt_axis(cfg, "I2SO.1", "I2SO.2", cfg.drive.invert_left),
        "y": _belt_axis(cfg, "I2SO.5", "I2SO.6", cfg.drive.invert_right),
    }
    for letter, spec in servo_axes(cfg):
        axes[letter] = _servo_axis(spec)
    return {
        "name": "wbbot V-plotter",
        "board": "MKS DLC32 V2.1",
        "meta": "generated by wbot for FluidNC 3.9 (kinematics key WallPlotter)",
        "stepping": {"engine": "I2S_STATIC", "idle_ms": IDLE_MS, "pulse_us": 4,
                     "dir_delay_us": 1, "disable_delay_us": 0},
        "i2so": {"bck_pin": "gpio.16", "data_pin": "gpio.21", "ws_pin": "gpio.17"},
        "kinematics": {KINEMATICS_NAME: {
            "left_axis": 0, "left_anchor_x": float(lx), "left_anchor_y": float(ly),
            "right_axis": 1, "right_anchor_x": float(rx), "right_anchor_y": float(ry),
            "segment_length": float(cfg.firmware.segment_length_mm)}},
        "axes": axes,
        "start": {"must_home": False, "deactivate_parking": True},
        "arc_tolerance_mm": 0.002,
        "junction_deviation_mm": float(cfg.motion.junction_deviation_mm),
        "verbose_errors": True,
        "report_inches": False,
        "enable_parking_override_control": False,
        "use_line_numbers": False,
    }


# ---------------------------------------------------------------------------
# text generation
# ---------------------------------------------------------------------------
def _y(obj: dict, indent: int = 0) -> str:
    text = yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=1000)
    pad = " " * indent
    return "".join(pad + ln + "\n" for ln in text.splitlines())


def _c(lines: str, indent: int = 0) -> str:
    pad = " " * indent
    return "".join(f"{pad}# {ln}".rstrip() + "\n" for ln in lines.strip("\n").splitlines())


_HEADER = """
=====================================================================
FluidNC-Konfiguration fuer den W-BOT V-Wandplotter (generiert von wbot)
Board: MKS DLC32 V2.1 (ESP32), FluidNC v3.9.x
Diese Datei wird aus config/wbot.yaml erzeugt - nicht von Hand aendern.
Hochladen: wbot.xmodem_upload.upload_config(), danach Controller neu starten.
=====================================================================

PRUEFEN NACH DEM NEUSTART (Boot-Log bzw. $CD):
  - "Kinematic system: WallPlotter"   (sonst laeuft die Maschine KARTESISCH,
    siehe D-029: ein falscher Block-Name wird still ignoriert, nur eine
    "Ignored key"-Zeile warnt)
  - keine "[MSG:ERR:"-Zeilen
  - "Axis Z (-44.000,44.000)" und bei aktivem Revolver "Axis A (0.000,180.000)"
  wbot.fluidnc_config.check_boot_log() und verify_dump() machen das automatisch.

SICHERHEIT: keine Endschalter -> kein Homing, keine Soft-Limits in der Firmware.
Den erlaubten Bereich erzwingt die Host-Software (wbot) vor jedem Befehl.
"""

_STEPPING = """
stepping.idle_ms MUSS 255 sein (= Motoren nie abschalten, D-033). Das Feld ist ein
Byte (max 254); alles Kleinere schaltet nach Millisekunden das Servo-Signal ab
(Servo schwingt wild) und die Riemenmotoren stromlos (Gondel faellt).
"""

_KINEMATICS = """
Der Block heisst WallPlotter (C++-Klassenname, D-029) - NICHT wall_plotter.
Die Firmware rechnet naiv: Riemenlaenge = Abstand Ankermittelpunkt -> Stift.
Die exakte Tangenten-Korrektur macht die Host-Software durch Vorverzerrung.
Achse X = linker Riemen, Achse Y = rechter Riemen.
"""

_BELTS = """
Riemenachsen X/Y: steps_per_mm = {spm:g} (200 Schritte * {ms} Mikroschritte / ({teeth} Zaehne * {pitch:g} mm)).
Ein ':low' hinter dem Richtungs-Pin invertiert die Drehrichtung.
"""

_SERVO_PEN = """
Servo B = Stift (MG90S, {pin}), Achse Z. 1000..2000 us = 180 Grad = 5.556 us/Grad (D-032 korrigiert).
Pulsfenster {lo}..{hi} us = Pulse bei +-{deg:g} Grad - das ist die harte mechanische Grenze,
FluidNC klemmt jede Position darauf. Achse {amin:g}..{amax:g}: positive_direction false +
mpos_mm {amin:g} -> Achse 0 = Servo-Mitte = Stellung beim Einschalten (D-030, D-031).
"""

_SERVO_REV = """
Servo A = Revolver (MG90S, {pin}), Achse A. Achse {amin:g}..{amax:g} ueber {lo}..{hi} us
(1000..2000 us = 180 Grad). Mechanisch -60/0/+60 Grad = Achsenwert 30/90/150.
"""

_NO_REVOLVER = """
SERVO-ACHSE A ENTFERNT (Revolver in config/wbot.yaml deaktiviert).
Der Pin wird nicht angesteuert, der Servo bleibt schlaff. Farbwechsel sind dann nicht moeglich.
output_pin: NO_PIN ist KEIN Ersatz: FluidNC meldet 'RC Servo disabled: No output pin',
markiert die GESAMTE Konfiguration als ungueltig und lehnt jeden Fahrbefehl mit error:9
ab. Die Achse muss fehlen, nicht pinlos sein.
"""


def generate_firmware_config(cfg: Config) -> str:
    """FluidNC 3.9 YAML text for ``cfg`` (ASCII only, ends with a newline)."""
    exp = expected_config(cfg)
    d = cfg.drive
    out = [_c(_HEADER)]
    out.append(_y({k: exp[k] for k in ("name", "board", "meta")}))
    out.append(_c(_STEPPING))
    out.append(_y({"stepping": exp["stepping"], "i2so": exp["i2so"]}))
    out.append(_c(_KINEMATICS))
    out.append(_y({"kinematics": exp["kinematics"]}))
    out.append(_c("Achsen. Reihenfolge: X (links), Y (rechts), Z (Stift), A (Revolver)."))
    out.append("axes:\n")
    out.append(_y({"shared_stepper_disable_pin": "I2SO.0"}, 2))
    out.append(_c(_BELTS.format(spm=cfg.steps_per_mm, ms=d.microsteps, teeth=d.pulley_teeth,
                                pitch=d.belt_pitch_mm), 2))
    axes = exp["axes"]
    out.append(_y({"x": axes["x"]}, 2))
    out.append(_y({"y": axes["y"]}, 2))
    for letter, spec in servo_axes(cfg):
        m = ServoModel(spec)
        tpl = _SERVO_PEN if spec is cfg.servos.pen else _SERVO_REV
        out.append(_c(tpl.format(pin=spec.pin, lo=m.fw_min_us, hi=m.fw_max_us, deg=spec.max_deg,
                                 amin=spec.axis_min, amax=spec.axis_min + spec.axis_travel), 2))
        out.append(_y({letter: axes[letter]}, 2))
    if not cfg.servos.revolver.enabled:
        out.append(_c(_NO_REVOLVER, 2))
    rest = {k: exp[k] for k in ("start", "arc_tolerance_mm", "junction_deviation_mm", "verbose_errors",
                                "report_inches", "enable_parking_override_control",
                                "use_line_numbers")}
    out.append(_y(rest))
    return "".join(out)


# ---------------------------------------------------------------------------
# $CD dump verification
# ---------------------------------------------------------------------------
_MISSING = object()
_CHATTER = re.compile(r"^\s*(ok|error:\d+|\[.*\]|<.*>|\$CD.*|\$Config/Dump.*)\s*$", re.IGNORECASE)


def parse_dump(text: str) -> dict | None:
    """Parse the YAML FluidNC prints for ``$CD`` (ignoring ``ok``/``[MSG..]`` chatter)."""
    body = "\n".join(ln for ln in text.replace("\r", "").split("\n") if not _CHATTER.match(ln))
    try:
        data = yaml.safe_load(body)
    except yaml.YAMLError as exc:
        log.warning("dump not parseable: %s", exc)
        return None
    return data if isinstance(data, dict) else None


def _get(d: Any, path: str) -> Any:
    cur = d
    for part in path.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return _MISSING
        cur = cur[part]
    return cur


def _same(exp: Any, act: Any, tol: float) -> bool:
    if isinstance(exp, bool):
        if isinstance(act, str):
            act = act.strip().lower() in ("true", "yes", "1", "on")
        return bool(act) == exp
    if isinstance(exp, (int, float)):
        try:
            return abs(float(act) - float(exp)) <= tol
        except (TypeError, ValueError):
            return False
    return str(act).strip().lower().replace(" ", "") == str(exp).strip().lower().replace(" ", "")


class _Check:
    def __init__(self, dump: dict) -> None:
        self.dump = dump
        self.issues: list[Issue] = []

    def eq(self, path: str, expected: Any, *, sev: Literal["error", "warn"] = "error",
           missing_sev: Literal["error", "warn"] | None = None, hint: str = "", tol: float = 1e-3) -> None:
        act = _get(self.dump, path)
        if act is _MISSING:
            sev2 = missing_sev or sev
            self.issues.append(Issue(sev2, path, expected, None,
                                     f"{path}: fehlt im Dump (erwartet: {expected}). {hint}".strip()))
        elif not _same(expected, act, tol):
            self.issues.append(Issue(sev, path, expected, act,
                                     f"{path}: erwartet {expected}, im Dump {act}. {hint}".strip()))


def _check_axis(c: _Check, letter: str, exp: dict) -> None:
    base = f"axes.{letter}"
    if _get(c.dump, base) is _MISSING:
        c.issues.append(Issue("error", base, "vorhanden", None,
                              f"Achse {letter.upper()} fehlt in der laufenden Konfiguration."))
        return
    c.eq(f"{base}.steps_per_mm", exp["steps_per_mm"])
    c.eq(f"{base}.max_rate_mm_per_min", exp["max_rate_mm_per_min"], sev="warn")
    c.eq(f"{base}.acceleration_mm_per_sec2", exp["acceleration_mm_per_sec2"], sev="warn")
    c.eq(f"{base}.max_travel_mm", exp["max_travel_mm"],
         hint="Bei Servo-Achsen bestimmt das den Winkelbereich." if "rc_servo" in exp["motor0"] else "")
    c.eq(f"{base}.soft_limits", False, missing_sev="warn")
    c.eq(f"{base}.homing.cycle", 0, hint="Ohne Endschalter darf nichts referenzieren.", missing_sev="warn")
    motor = exp["motor0"]
    if "stepstick" in motor:
        for k in ("step_pin", "direction_pin"):
            c.eq(f"{base}.motor0.stepstick.{k}", motor["stepstick"][k])
        return
    rc = motor["rc_servo"]
    c.eq(f"{base}.motor0.rc_servo.output_pin", rc["output_pin"])
    c.eq(f"{base}.motor0.rc_servo.pwm_hz", rc["pwm_hz"], sev="warn")
    for k in ("min_pulse_us", "max_pulse_us"):
        c.eq(f"{base}.motor0.rc_servo.{k}", rc[k], tol=0.5,
             hint="Das Pulsfenster ist die harte mechanische Grenze.")
    hom = exp["homing"]
    c.eq(f"{base}.homing.positive_direction", False,
         hint="Sonst werden alle positiven Winkel auf denselben Puls geklemmt (D-030).")
    c.eq(f"{base}.homing.mpos_mm", hom["mpos_mm"], hint="Legt den Achsenbereich fest (D-030/D-032).")


def verify_dump(cfg: Config, dump_text: str) -> list[Issue]:
    """Compare a ``$CD`` dump with what :func:`generate_firmware_config` produces.

    Keys the dump has in addition (FluidNC prints all defaults) are ignored.
    """
    dump = parse_dump(dump_text)
    if dump is None:
        return [Issue("error", "dump", "YAML", None,
                      "Der $CD-Dump ist leer oder kein lesbares YAML (Verbindung/Antwort pruefen).")]
    exp = expected_config(cfg)
    c = _Check(dump)

    kin = dump.get("kinematics")
    names = list(kin) if isinstance(kin, dict) else []
    if KINEMATICS_NAME not in names:
        c.issues.append(Issue(
            "error", "kinematics", KINEMATICS_NAME, ", ".join(map(str, names)) or None,
            f"Kinematik-Block '{KINEMATICS_NAME}' fehlt (gefunden: {names or 'keiner'}). "
            "FluidNC laeuft dann kartesisch und setzt jede Koordinate falsch (D-029)."))
    else:
        for k, v in exp["kinematics"][KINEMATICS_NAME].items():
            c.eq(f"kinematics.{KINEMATICS_NAME}.{k}", v)
        extra = [n for n in names if n != KINEMATICS_NAME]
        if extra:
            c.issues.append(Issue("warn", "kinematics", KINEMATICS_NAME, names,
                                  f"Zusaetzliche Kinematik-Bloecke im Dump: {extra}."))

    c.eq("stepping.engine", exp["stepping"]["engine"])
    c.eq("stepping.idle_ms", IDLE_MS,
         hint="Muss 255 sein, sonst wird das Servo-Signal abgeschaltet und die Gondel stromlos (D-033).")
    for k in ("pulse_us", "dir_delay_us", "disable_delay_us"):
        c.eq(f"stepping.{k}", exp["stepping"][k], sev="warn")
    for k, v in exp["i2so"].items():
        c.eq(f"i2so.{k}", v)
    c.eq("axes.shared_stepper_disable_pin", exp["axes"]["shared_stepper_disable_pin"])
    c.eq("start.must_home", False, missing_sev="warn", hint="Ohne Endschalter kein Homing.")
    c.eq("junction_deviation_mm", exp["junction_deviation_mm"], sev="warn", missing_sev="warn")

    for letter in ("x", "y", *[k for k, _ in servo_axes(cfg)]):
        _check_axis(c, letter, exp["axes"][letter])
    axes = dump.get("axes") if isinstance(dump.get("axes"), dict) else {}
    for letter in _AXIS_ORDER:
        if letter not in exp["axes"] and isinstance(axes.get(letter), dict) and axes[letter].get("motor0"):
            c.issues.append(Issue(
                "warn", f"axes.{letter}", "nicht vorhanden", "vorhanden",
                f"Achse {letter.upper()} ist in der Firmware konfiguriert, aber in wbot deaktiviert."))
    return c.issues


# ---------------------------------------------------------------------------
# boot log check
# ---------------------------------------------------------------------------
_RE_KIN = re.compile(r"Kinematic system:\s*([A-Za-z_]+)")
_RE_AXCOUNT = re.compile(r"Axis count\s+(\d+)")
_RE_AXRANGE = re.compile(r"Axis ([XYZABC]) \((-?\d+(?:\.\d+)?),\s*(-?\d+(?:\.\d+)?)\)")


def check_boot_log(text: str, cfg: Config | None = None) -> list[Issue]:
    """Check the FluidNC boot log (also fine with the log of several boots).

    Without ``cfg`` the revolver is assumed enabled and the default servo ranges are used.
    """
    cfg = cfg or Config()
    issues: list[Issue] = []
    kin = _RE_KIN.findall(text)
    if not kin:
        issues.append(Issue("error", "kinematics", KINEMATICS_NAME, None,
                            "Im Boot-Log fehlt 'Kinematic system: WallPlotter' (Log unvollstaendig "
                            "oder Kinematik nicht geladen)."))
    elif kin[-1] != KINEMATICS_NAME:
        issues.append(Issue("error", "kinematics", KINEMATICS_NAME, kin[-1],
                            f"Kinematik ist '{kin[-1]}' statt '{KINEMATICS_NAME}': die Maschine "
                            "faehrt falsch (D-029)."))
    for ln in text.replace("\r", "").split("\n"):
        if "Ignored key" in ln:
            key = ln.split("Ignored key", 1)[1].strip(" ]")
            issues.append(Issue("error", f"ignored_key.{key}", None, key,
                                f"FluidNC ignoriert den Schluessel '{key}' (Tippfehler/falsche "
                                "Schreibweise; evtl. kartesischer Betrieb)."))
        elif "[MSG:ERR:" in ln:
            issues.append(Issue("error", "boot_error", None, ln.strip(),
                                f"Fehlermeldung im Boot-Log: {ln.strip()}"))
        elif "Configuration is invalid" in ln or "RC Servo disabled" in ln:
            issues.append(Issue("error", "config_invalid", None, ln.strip(),
                                f"Konfiguration ungueltig: {ln.strip()}"))
    servos = {k.upper(): s for k, s in servo_axes(cfg)}
    want = 2 + len(servos)
    cnt = _RE_AXCOUNT.findall(text)
    if not cnt:
        issues.append(Issue("warn", "axis_count", want, None, "Im Boot-Log fehlt 'Axis count'."))
    elif int(cnt[-1]) != want:
        issues.append(Issue("error", "axis_count", want, int(cnt[-1]),
                            f"Achsenzahl {cnt[-1]} statt {want} (X, Y, Z"
                            f"{', A' if cfg.servos.revolver.enabled else ''})."))
    ranges = {m[0]: (float(m[1]), float(m[2])) for m in _RE_AXRANGE.findall(text)}
    for axis, got in ranges.items():
        spec = servos.get(axis)
        if axis in ("Z", "A") and spec is None:
            issues.append(Issue("error", f"axis_range.{axis}", None, got,
                                f"Achse {axis} taucht im Boot-Log auf, ist aber nicht erwartet."))
        elif spec is not None:
            want_rng = (float(spec.axis_min), float(spec.axis_min + spec.axis_travel))
            if abs(got[0] - want_rng[0]) > 1e-3 or abs(got[1] - want_rng[1]) > 1e-3:
                issues.append(Issue(
                    "error", f"axis_range.{axis}", want_rng, got,
                    f"Achse {axis} hat den Bereich {got}, erwartet {want_rng}. "
                    "Servo-Achsen brauchen positive_direction: false (D-030)."))
    return issues


