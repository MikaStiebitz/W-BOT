"""Generate the FluidNC firmware config from ``machine.yaml``.

**Read this before flashing anything.**

The brief is explicit that the ``wallplotter`` parameter names have changed
between FluidNC versions and must be verified against the firmware actually
installed.  That is honoured here in three ways:

1. generation is **versioned** — :data:`SCHEMAS` holds one generator per
   firmware generation, selected by ``schema`` (default ``"3.7"``);
2. the generated file carries a **verification header** listing exactly which
   keys to check with ``$CD`` / ``$Config/Dump`` on the real controller;
3. :func:`verify_against_controller` compares a dump from the machine with
   what we generated and reports the differences, so the check is mechanical
   rather than a memory exercise.

Nothing here talks to the hardware by itself. Generate, read, then flash.
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import yaml

from ..config import MachineConfig, to_plain

__all__ = [
    "SCHEMAS",
    "DEFAULT_SCHEMA",
    "generate_fluidnc_config",
    "write_fluidnc_config",
    "verify_against_controller",
    "VERIFY_KEYS",
]

DEFAULT_SCHEMA = "3.7"

#: Keys whose spelling is known to have moved between FluidNC generations.
#: These are the ones to check first against ``$CD`` output.
VERIFY_KEYS = (
    "kinematics.wall_plotter.left_anchor_x",
    "kinematics.wall_plotter.left_anchor_y",
    "kinematics.wall_plotter.right_anchor_x",
    "kinematics.wall_plotter.right_anchor_y",
    "kinematics.wall_plotter.segment_length",
    "axes.z.motor0.rc_servo.output_pin",
    "axes.a.motor0.rc_servo.output_pin",
    "stepping.engine",
)


def _header(cfg: MachineConfig, schema: str) -> str:
    return textwrap.dedent(f"""\
        # =====================================================================
        # FluidNC configuration generated by wbbot for schema "{schema}"
        # Board: MKS DLC32 V2.1 (ESP32)   Machine: V-plotter, {cfg.board.width_mm:.0f}
        # x {cfg.board.height_mm:.0f} mm
        # =====================================================================
        #
        # VERIFY BEFORE FLASHING
        # ----------------------
        # FluidNC has renamed wallplotter and servo keys between releases. Dump
        # the running configuration with
        #
        #     $CD            (or $Config/Dump)
        #
        # and compare at least these keys against this file:
        #
        {chr(10).join('        #   - ' + k for k in VERIFY_KEYS)}
        #
        # If any of them differ, regenerate with a matching schema:
        #
        #     wbbot fluidnc-config --schema <version>
        #
        # and record what changed in DECISIONS.md. Do not silently edit this
        # file: it is regenerated from config/machine.yaml.
        #
        # SAFETY
        # ------
        # There are no limit switches on this machine, so homing is disabled and
        # soft limits are off. The host software (wbbot) enforces the safe area
        # before any coordinate is sent. Do not enable soft_limits here without
        # first setting a reliable machine zero.
        # =====================================================================
        """)


def _axis_block(steps_per_mm: float, max_rate: float, accel: float,
                max_travel: float) -> dict:
    return {
        "steps_per_mm": round(steps_per_mm, 4),
        "max_rate_mm_per_min": round(max_rate, 1),
        "acceleration_mm_per_sec2": round(accel, 1),
        "max_travel_mm": round(max_travel, 1),
        "soft_limits": False,
        "homing": {"cycle": 0},          # 0 = not homed by $H
    }


def _stepper_motor(step_pin: str, direction_pin: str,
                   invert_direction: bool) -> dict:
    """One stepstick motor block.

    Deliberately **no** ``disable_pin``: the DLC32 wires both drivers to a
    single enable line, which is declared once as
    ``axes.shared_stepper_disable_pin``. Naming the same pin again here makes
    FluidNC reject the whole file with "pin is already used", and the board
    then falls back to its built-in defaults — which look like the config
    loaded but move the machine with the wrong kinematics.
    """
    return {
        "stepstick": {
            "step_pin": step_pin,
            "direction_pin": (direction_pin + ":low") if invert_direction
                             else direction_pin,
        }
    }


def _servo_motor(pin: str, pwm_hz: int, min_us: int, max_us: int) -> dict:
    return {
        "rc_servo": {
            "output_pin": pin,
            "pwm_hz": pwm_hz,
            "min_pulse_us": min_us,
            "max_pulse_us": max_us,
        }
    }


def _generate_37(cfg: MachineConfig) -> dict:
    """FluidNC 3.7-style configuration."""
    drive = cfg.drive
    motion = cfg.motion
    geo = cfg.geometry
    pen = cfg.servo.pen
    rev = cfg.servo.revolver

    # Belt length range the gondola actually needs, plus headroom.
    span = geo.anchor_distance_mm
    max_belt = span + cfg.board.height_mm

    idle_ms = 255
    if cfg.servo.idle_disable:
        # FluidNC disables the motors after idle_ms; 255 means "never".
        idle_ms = int(min(max(cfg.servo.idle_disable_after_s * 1000.0, 0), 254))

    config: dict = {
        "name": "wbbot V-plotter",
        "board": "MKS DLC32 V2.1",
        "meta": "generated by wbbot - do not edit by hand",

        "stepping": {
            "engine": "I2S_STATIC",
            "idle_ms": idle_ms,
            "pulse_us": 4,
            "dir_delay_us": 1,
            "disable_delay_us": 0,
        },

        "kinematics": {
            "wall_plotter": {
                "left_axis": 0,
                "left_anchor_x": round(geo.anchor_left[0], 3),
                "left_anchor_y": round(geo.anchor_left[1], 3),
                "right_axis": 1,
                "right_anchor_x": round(geo.anchor_right[0], 3),
                "right_anchor_y": round(geo.anchor_right[1], 3),
                # Long moves are broken into segments so the belt-length
                # interpolation stays close to a straight cartesian line.
                "segment_length": 1.0,
            }
        },

        "axes": {
            "shared_stepper_disable_pin": "I2SO.0",
            "x": {
                **_axis_block(drive.steps_per_mm_left,
                              motion.travel_feed_mm_min,
                              motion.acceleration_mm_s2, max_belt),
                "motor0": _stepper_motor("I2SO.1", "I2SO.2",
                                         drive.invert_left),
            },
            "y": {
                **_axis_block(drive.steps_per_mm_right,
                              motion.travel_feed_mm_min,
                              motion.acceleration_mm_s2, max_belt),
                "motor0": _stepper_motor("I2SO.5", "I2SO.6",
                                         drive.invert_right),
            },
            "z": {
                # A servo axis is positioned, not stepped: 1 step/unit keeps
                # G-code units identical to the degrees the tuner shows.
                "steps_per_mm": 1.0,
                "max_rate_mm_per_min": round(cfg.servo.feed_units_min, 1),
                "acceleration_mm_per_sec2": 1000.0,
                "max_travel_mm": round(pen.axis_max_travel, 1),
                "soft_limits": False,
                "homing": {"cycle": 0},
                "motor0": _servo_motor(pen.output_pin, pen.pwm_hz,
                                       pen.min_pulse_us, pen.max_pulse_us),
            },
            "a": {
                "steps_per_mm": 1.0,
                "max_rate_mm_per_min": round(cfg.servo.feed_units_min, 1),
                "acceleration_mm_per_sec2": 1000.0,
                "max_travel_mm": round(rev.axis_max_travel, 1),
                "soft_limits": False,
                "homing": {"cycle": 0},
                "motor0": _servo_motor(rev.output_pin, rev.pwm_hz,
                                       rev.min_pulse_us, rev.max_pulse_us),
            },
        },

        "start": {
            "must_home": False,
            "deactivate_parking": True,
        },

        "arc_tolerance_mm": 0.002,
        "junction_deviation_mm": round(motion.junction_deviation_mm, 4),
        "verbose_errors": True,
        "report_inches": False,
        "enable_parking_override_control": False,
        "use_line_numbers": False,
    }
    return config


def _generate_36(cfg: MachineConfig) -> dict:
    """FluidNC 3.6-style: the wallplotter block used a different spelling."""
    config = _generate_37(cfg)
    geo = cfg.geometry
    config["kinematics"] = {
        "wallplotter": {
            "left_axis": 0,
            "left_anchor_x": round(geo.anchor_left[0], 3),
            "left_anchor_y": round(geo.anchor_left[1], 3),
            "right_axis": 1,
            "right_anchor_x": round(geo.anchor_right[0], 3),
            "right_anchor_y": round(geo.anchor_right[1], 3),
            "segment_length": 1.0,
        }
    }
    config["meta"] = ("generated by wbbot for FluidNC 3.6 "
                      "(kinematics key: 'wallplotter')")
    return config


#: Available schema generators, newest first.
SCHEMAS: dict[str, Callable[[MachineConfig], dict]] = {
    "3.7": _generate_37,
    "3.6": _generate_36,
}


def generate_fluidnc_config(cfg: MachineConfig,
                            schema: str = DEFAULT_SCHEMA) -> str:
    """Return the FluidNC YAML text for this machine."""
    if schema not in SCHEMAS:
        raise ValueError(
            f"unknown FluidNC schema {schema!r}; available: "
            f"{', '.join(sorted(SCHEMAS))}")
    body = yaml.safe_dump(to_plain(SCHEMAS[schema](cfg)), sort_keys=False,
                          default_flow_style=False, allow_unicode=False)
    return _header(cfg, schema) + body


def write_fluidnc_config(cfg: MachineConfig, path: str | Path | None = None,
                         schema: str = DEFAULT_SCHEMA) -> Path:
    """Write ``config/fluidnc/config.yaml`` (or wherever you point it)."""
    from ..config import default_config_dir
    target = Path(path) if path else default_config_dir() / "fluidnc" / "config.yaml"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate_fluidnc_config(cfg, schema), encoding="utf-8")
    return target


def _flatten(data: dict, prefix: str = "") -> dict[str, object]:
    out: dict[str, object] = {}
    for key, value in data.items():
        path = f"{prefix}.{key}" if prefix else str(key)
        if isinstance(value, dict):
            out.update(_flatten(value, path))
        else:
            out[path] = value
    return out


def verify_against_controller(cfg: MachineConfig, dumped_yaml: str,
                              schema: str = DEFAULT_SCHEMA) -> dict:
    """Compare a ``$CD`` dump from the controller with what we would generate.

    Returns a report of missing keys and value mismatches, so "did the firmware
    rename something" is a mechanical check rather than a guess.
    """
    try:
        actual_raw = yaml.safe_load(dumped_yaml) or {}
    except yaml.YAMLError as exc:
        return {"ok": False,
                "error": f"the controller dump is not valid YAML: {exc}"}
    if not isinstance(actual_raw, dict):
        return {"ok": False, "error": "the controller dump is not a mapping"}

    expected = _flatten(SCHEMAS[schema](cfg))
    actual = _flatten(actual_raw)

    missing: list[str] = []
    mismatched: list[dict] = []
    for key in VERIFY_KEYS:
        if key not in actual:
            missing.append(key)
        elif key in expected and str(actual[key]) != str(expected[key]):
            mismatched.append({"key": key, "expected": expected[key],
                               "on_controller": actual[key]})

    notes: list[str] = []
    if missing:
        alt_keys = [k for k in actual
                    if "anchor" in k.lower() or "servo" in k.lower()]
        notes.append(
            f"{len(missing)} expected key(s) are absent from the controller "
            f"dump. Similar keys present: {', '.join(sorted(alt_keys)[:8]) or 'none'}. "
            f"If the names differ, add a schema in fluidnc_config.SCHEMAS "
            f"rather than editing the generated file.")
    return {
        "ok": not missing and not mismatched,
        "schema": schema,
        "missing_keys": missing,
        "mismatched": mismatched,
        "checked": list(VERIFY_KEYS),
        "notes": notes,
    }
